"use strict";

// Runs in the existing Chromium fixture, using the real Maintenance scripts/DOM.
(async () => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const el = (name) => document.getElementById(`system-${name}`);
  const tick = () => new Promise((resolve) => setTimeout(resolve, 10));
  const until = async (condition) => {
    for (let count = 0; count < 100 && !condition(); ++count) await tick();
    assert(condition(), "Timed out waiting for system UI");
  };
  const reads = () => fixture.requests.filter((item) => item.path.endsWith("system/details")).length;
  const row = (target, label) => Array.from(target.querySelectorAll("dl > div"))
    .find((item) => item.querySelector("dt").textContent === label).querySelector("dd");
  const assertFits = () => assert(document.documentElement.scrollWidth <= innerWidth,
    `System page overflows ${innerWidth}px viewport: ${document.documentElement.scrollWidth}px`);

  if (fixture.mode === "format") {
    assert(systemBytes(0) === "0.0 MiB", "zero must remain an observed value");
    assert(systemBytes(64 * 1024 ** 2) === "64.0 MiB", "MiB formatting");
    assert(systemBytes(1.5 * 1024 ** 3) === "1.50 GiB", "GiB formatting");
    for (const value of [null, undefined, -1, NaN, Infinity]) assert(systemBytes(value) === "Unavailable", "invalid sizes must be explicit");
    assert(systemUptime(90061.9) === "1d 1h 1m 1s", "uptime formatting");
    assert(systemUptime(0) === "0d 0h 0m 0s", "zero uptime");
    assert(systemUptime(null) === "Unavailable", "missing uptime");
    assert(systemSelection({status: "none", name: null}) === "None selected", "empty selection differs from unreadable state");
    assert(systemSelection({status: "unavailable", name: null}) === "Unavailable", "unreadable selection");
    assert(systemMeter(null, 100, "test") === "Unavailable", "missing usage must not become zero");
    assert(systemMeter(1, 0, "test") === "Unavailable", "zero total has no percentage");
    const meter = systemMeter(25, 100, "test").querySelector("meter");
    assert(meter.value === 25 && meter.max === 100 && meter.getAttribute("aria-label") === "test", "meter must represent supplied values accessibly");
    fixture.data.platform.hostname = "<img src=x onerror=alert(1)>";
    systemRender(fixture.data);
    assert(el("platform").textContent.includes("<img src=x"), "device strings must render as text");
    assert(!el("platform").querySelector("img"), "device strings must not create markup");
  } else if (fixture.mode === "page") {
    await until(() => !el("information").hidden);
    assert(reads() === 1, "direct #system navigation must load one snapshot");
    assert(!fixture.requests.some((item) => /apps\/|ota\//.test(item.path)), "System must not invoke other management workflows");
    assert(document.querySelector('a[href="#system"]').getAttribute("aria-current") === "page", "System navigation must be active");
    assert(document.getElementById("overview-view").hidden && document.getElementById("apps-view").hidden, "System must be an independent view");
    assert(el("platform").textContent.includes("Fixture board"), "platform fields must be visible");
    const ram = el("memory").querySelector("meter");
    assert(ram.value / ram.max === 0.25, "RAM must reflect MemAvailable-based backend usage");
    assert(el("storage").textContent.includes("/dev/fixture-sys") && el("storage").textContent.includes("/dev/fixture-home"), "SYS and HOME use observed devices");
    assert(el("storage").querySelectorAll("meter").length === 2, "both storage roles need usage meters");
    assert(el("boot").textContent.includes("B") && el("boot").textContent.includes("/dev/mmcblk0p8"), "boot mapping must be rendered");
    assert(el("network-route").textContent.includes("eth0"), "default route must be visible");
    assert(el("network").textContent.includes("192.0.2.7") && el("network").querySelector(".status-ok"), "network address and indicator");
    const camera = row(document.getElementById("system-view"), "Camera").querySelector("span");
    assert(camera.classList.contains("status-error"), "failed camera service must show an error indicator");
    const color = getComputedStyle(camera).color.match(/\d+/g).map(Number);
    assert(color[0] > color[1], "error indicator must be red");
    const usbDetails = el("usb").closest("details");
    assert(!usbDetails.open, "USB list must start collapsed");
    usbDetails.querySelector("summary").click();
    assert(usbDetails.open && el("usb").textContent.includes("uvcvideo"), "USB details and driver must expand");
    assert(el("usb").textContent.includes("1-1.2"), "USB connections must be visible");
    assertFits();
    assert(usbDetails.getBoundingClientRect().height <= innerHeight * 0.66, "long USB lists must scroll within the screen");
    const before = reads();
    fixture.hold = true;
    fixture.data.platform.version = "2026.5.b";
    el("refresh").click();
    await until(() => Boolean(fixture.release));
    assert(el("refresh").disabled && el("information").getAttribute("aria-busy") === "true", "refresh must communicate loading");
    el("refresh").click();
    await systemLoad();
    assert(reads() === before + 1, "concurrent refresh must not duplicate requests");
    fixture.release();
    await until(() => !el("refresh").disabled);
    assert(el("platform").textContent.includes("2026.5.b"), "Refresh must replace old values");
    fixture.fail = 500;
    el("refresh").click();
    await until(() => !el("info-error").hidden);
    assert(el("information").hidden && el("info-error").textContent.includes("fixture unavailable"), "failed refresh must not present old data as current");
    fixture.fail = null;
    el("refresh").click();
    await until(() => !el("information").hidden);
    assert(el("info-error").hidden, "successful retry must clear stale error");
    const noPoll = reads();
    await new Promise((resolve) => setTimeout(resolve, 1200));
    assert(reads() === noPoll, "system page must not poll");
    document.querySelector('a[href="#overview"]').click();
    await until(() => !document.getElementById("overview-view").hidden);
    assert(document.getElementById("system-version").textContent === "2026.5.a", "compact Overview must remain independent");
    document.querySelector('a[href="#apps"]').click();
    await until(() => fixture.requests.some((item) => item.path.endsWith("apps/status")));
    assert(!document.getElementById("apps-view").hidden, "Apps navigation remains usable");
    document.querySelector('a[href="#updates"]').click();
    await until(() => fixture.requests.some((item) => item.path.endsWith("ota/status")));
    assert(!document.getElementById("updates-view").hidden, "System Updates navigation remains usable");
    document.querySelector('a[href="#system"]').click();
    await until(() => reads() === noPoll + 1 && !el("refresh").disabled);
    assertFits();
    assert(fixture.requests.every((item) => item.method === "GET"), "navigation and refresh must remain read-only");
  } else if (fixture.mode === "access") {
    await until(() => document.getElementById("admin-action").textContent === "Unlock");
    assert(reads() === 0 && el("refresh").disabled && !el("locked").hidden, "locked browser must not fetch protected information");
    fixture.data.platform.cpu_model = null;
    fixture.data.memory.available_bytes = null;
    fixture.data.memory.used_bytes = null;
    fixture.data.network.interfaces = null;
    fixture.data.network.default_ipv4_routes = null;
    fixture.data.network.default_ipv4_route = null;
    fixture.data.usb = null;
    fixture.data.maintenance.ota = null;
    renderAuth({authenticated: true, csrf_token: "fixture-csrf"});
    await until(() => !el("information").hidden);
    assert(row(document.getElementById("system-view"), "CPU model").textContent === "Unavailable", "missing CPU must be explicit");
    assert(row(document.getElementById("system-view"), "Used RAM").textContent === "Unavailable", "missing MemAvailable must not show false usage");
    assert(!el("memory").querySelector("meter"), "unknown RAM usage must not show a fabricated bar");
    assert(el("network").textContent === "Unavailable" && el("usb-count").textContent === "Unavailable", "unreadable device sections must be explicit");
    fixture.hold = true;
    el("refresh").click();
    await until(() => Boolean(fixture.release));
    renderAuth({authenticated: false});
    fixture.release();
    await tick();
    assert(el("information").hidden && !el("locked").hidden, "lock must invalidate an in-flight snapshot");
    assert(!el("platform").textContent && !el("network").textContent, "locking must clear private data from DOM");
    fixture.fail = 401;
    renderAuth({authenticated: true, csrf_token: "fixture-csrf"});
    await until(() => !el("locked").hidden);
    assert(el("information").hidden && el("refresh").disabled, "expired session must restore locked view");
  }
  assert(!fixture.errors.length, `Unexpected JavaScript errors: ${fixture.errors.join("; ")}`);
  document.getElementById("browser-result").textContent = "PASS";
})().catch((error) => { document.getElementById("browser-result").textContent = "FAIL: " + error.stack; });
